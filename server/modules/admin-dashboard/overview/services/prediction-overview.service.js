import { PredictionHistory } from "../../../prediction-history/predictionHistory.model.js";
import { User } from "../../../users/user.model.js";
import { Course } from "../../../courses/course.model.js";

export const getPredictionOverview = async () => {

  const [
    totalPredictions,
    recentPredictions,
  ] = await Promise.all([

    /*
    |--------------------------------------------------------------------------
    | Total Predictions
    |--------------------------------------------------------------------------
    */

    PredictionHistory.countDocuments(),


    /*
    |--------------------------------------------------------------------------
    | Recent Predictions
    |--------------------------------------------------------------------------
    */

    PredictionHistory.aggregate([

      /*
      |--------------------------------------------------------------------------
      | Latest First
      |--------------------------------------------------------------------------
      */

      {
        $sort: {
          createdAt: -1,
        },
      },


      /*
      |--------------------------------------------------------------------------
      | Lookup User
      |--------------------------------------------------------------------------
      */

      {
        $lookup: {
          from: User.collection.name,
          localField: "userId",
          foreignField: "_id",
          as: "user",
        },
      },


      /*
      |--------------------------------------------------------------------------
      | Keep Only Predictions With Existing Users
      |--------------------------------------------------------------------------
      */

      {
        $match: {
          "user.0": {
            $exists: true,
          },
        },
      },


      /*
      |--------------------------------------------------------------------------
      | Latest 5 Valid Predictions
      |--------------------------------------------------------------------------
      */

      {
        $limit: 5,
      },


      /*
      |--------------------------------------------------------------------------
      | Lookup Course
      |--------------------------------------------------------------------------
      */

      {
        $lookup: {
          from: Course.collection.name,
          localField: "courseId",
          foreignField: "_id",
          as: "course",
        },
      },


      /*
      |--------------------------------------------------------------------------
      | Convert User Array To Object
      |--------------------------------------------------------------------------
      */

      {
        $unwind: {
          path: "$user",
        },
      },


      /*
      |--------------------------------------------------------------------------
      | Convert Course Array To Object
      |--------------------------------------------------------------------------
      */

      {
        $unwind: {
          path: "$course",
          preserveNullAndEmptyArrays: true,
        },
      },


      /*
      |--------------------------------------------------------------------------
      | Final Dashboard Data
      |--------------------------------------------------------------------------
      */

      {
        $project: {

          _id: 0,


          /*
          |--------------------------------------------------------------------------
          | Student Name
          |--------------------------------------------------------------------------
          */

          studentName: {

            $trim: {

              input: {

                $concat: [

                  {
                    $ifNull: [
                      "$user.firstName",
                      "",
                    ],
                  },

                  " ",

                  {
                    $ifNull: [
                      "$user.lastName",
                      "",
                    ],
                  },

                ],

              },

            },

          },


          /*
          |--------------------------------------------------------------------------
          | Course
          |--------------------------------------------------------------------------
          */

          course: {

            $ifNull: [
              "$course.name",
              "-",
            ],

          },


          /*
          |--------------------------------------------------------------------------
          | Rank
          |--------------------------------------------------------------------------
          */

          rank: {

            $ifNull: [

              {
                $arrayElemAt: [
                  "$predictedColleges.studentRank",
                  0,
                ],
              },

              "-",

            ],

          },


          /*
          |--------------------------------------------------------------------------
          | Result
          |--------------------------------------------------------------------------
          */

          result: {

            $concat: [

              {
                $toString: {

                  $ifNull: [
                    "$totalResults",
                    0,
                  ],

                },
              },

              " colleges",

            ],

          },


          /*
          |--------------------------------------------------------------------------
          | Date
          |--------------------------------------------------------------------------
          */

          date: "$createdAt",

        },
      },

    ]),

  ]);


  /*
  |--------------------------------------------------------------------------
  | Return Overview
  |--------------------------------------------------------------------------
  */

  return {

    predictions: {
      total: totalPredictions,
    },

    recentPredictions,

  };

};